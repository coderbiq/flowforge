class MetricsError(Exception):
    """User-facing extraction error (non-zero exit)."""


def open_ro(db_path):
    path = Path(db_path).expanduser()
    if not path.exists():
        raise MetricsError(f"database not found: {path}")
    uri = "file:" + urllib.parse.quote(str(path), safe="/:") + "?mode=ro"
    try:
        return sqlite3.connect(uri, uri=True)
    except sqlite3.Error as exc:
        raise MetricsError(f"cannot open database read-only: {path}: {exc}") from exc


def check_schema(conn):
    try:
        names = {row[0] for row in
                 conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    except sqlite3.DatabaseError as exc:
        raise MetricsError(f"not a SQLite database: {exc}") from exc
    missing = {"session", "part"} - names
    if missing:
        raise MetricsError(
            "opencode DB missing table(s): " + ", ".join(sorted(missing)))


def classify_verdict(output_text):
    """ok / fail / unknown for one bash part's output text."""
    if not isinstance(output_text, str):
        return "unknown"
    if "BUILD SUCCESSFUL" in output_text:
        return "ok"
    if "BUILD FAILED" in output_text:
        return "fail"
    match = EXIT_CODE_RE.search(output_text)
    if match and int(match.group(1)) != 0:
        return "fail"
    return "unknown"


def normalize_command(cmd):
    """Trim, collapse whitespace, truncate to 120 chars (requirement constraint)."""
    return WS_RE.sub(" ", cmd.strip())[:120]


def parse_epochs(spec):
    """Parse "name:<T,name:T1-T2,name:>T2" into [(name, lo, hi)] bounds (ms)."""
    if not spec:
        return None
    epochs = []
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        name, sep, bound = chunk.partition(":")
        if not sep:
            raise MetricsError(f"bad epoch chunk, expected name:bound: {chunk!r}")
        name, bound = name.strip(), bound.strip()
        try:
            if bound.startswith("<"):
                epochs.append((name, None, int(bound[1:])))  # ts < hi
            elif bound.startswith(">"):
                epochs.append((name, int(bound[1:]) + 1, None))  # ts > bound
            else:
                lo, sep2, hi = bound.partition("-")
                if not sep2:
                    raise ValueError(bound)
                epochs.append((name, int(lo), int(hi) + 1))  # T1 <= ts <= T2
        except ValueError as exc:
            raise MetricsError(
                f"bad epoch bound, expected <T, T1-T2 or >T: {chunk!r}") from exc
    return epochs or None


def epoch_label(ts, epochs):
    if not epochs:
        return "-"
    for name, lo, hi in epochs:
        if lo is not None and ts < lo:  # range lower bound inclusive
            continue
        if hi is not None and ts >= hi:  # '< T' strict, range upper inclusive
            continue
        return name
    return "-"


# --- report: epoch / strata / runaway constants (ticket 02; single source) ---

UNCLASSIFIED = "unclassified"
STRATA_ORDER = ("S", "M", "L", "unknown")
STRATA_S_MAX_CHANGES = 2   # S: changes <= 2 AND all evidence cmds unit-level
STRATA_L_MIN_CHANGES = 4   # L: changes >= 4 OR any heavy evidence cmd
RUNAWAY_STEPS = 150        # runaway: steps > 150 ...
RUNAWAY_REP_MAX = 10       # ... or rep_max > 10 ...
RUNAWAY_DUR_MIN = 30.0     # ... or dur_min > 30 (any one)

# --- decision gates (ticket 03; design d-decision-gates — pre-registered) ---
# Gate rules were registered BEFORE the observation window opened; the report
# only prints the current verdict against them. Changing a rule means revising
# the design authority first (d-decision-gates) — never this script alone.

HARDENED_EPOCH = "hardened"  # only the hardened epoch gates (d-epoch: the
#                             pre-hardening / provider-switch epochs are baselines)
GATE_MIN_N = 5               # per-side minimum n for a hard verdict
G2_COST_RATIO = 0.7          # flash cost median < flagship median x 0.7
G2_ROLLBACK_RATIO = 2.0      # design G2: fail with ratio >= 2x -> rollback
G3_DUR_RATIO = 1.5           # flash dur median <= flagship median x 1.5
G4_REP_MAX = 20              # circuit-break: rep_max >= 20 (right-inclusive)
G4_STEPS = 400               # circuit-break: steps >= 400 (right-inclusive)
GATE_PASS = "pass"
GATE_FAIL = "fail"
GATE_INSUFFICIENT = "insufficient-n"
GATE_NOT_TRIGGERED = "not-triggered"
_GATE_SEVERITY = {GATE_PASS: 0, GATE_NOT_TRIGGERED: 0,
                  GATE_INSUFFICIENT: 1, GATE_FAIL: 2}

