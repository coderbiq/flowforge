#!/usr/bin/env python3
"""Executor value metrics: extract flowforge-implementer session metrics from
the local opencode SQLite DB into an append-only observations.md.

Authorities:
- design: docs/proposals/executor-value-measurement/design.md (d-extraction, d-cost)
- requirements: docs/proposals/executor-value-measurement/requirements.md

Zero third-party dependencies (python3 stdlib only). The DB is always opened
read-only via a ``file:...?mode=ro`` URI; observations.md is append-only with
the session id as idempotency key.

Usage:
    python3 scripts/executor_metrics.py extract \
        --db ~/.local/share/opencode/opencode.db \
        --project tangram-v2 \
        --out docs/proposals/executor-value-measurement/observations.md \
        [--since <epoch-ms|ISO8601>] \
        [--epochs "name:<T,name:T1-T2,name:>T2"] \
        [--price-override '{"flash":[in,out,cacheR],...}']

    python3 scripts/executor_metrics.py report \
        --obs docs/proposals/executor-value-measurement/observations.md \
        [--out docs/proposals/executor-value-measurement/report.md] \
        [--epochs "name:<T,name:T1-T2,name:>T2"] \
        [--project-root /path/to/target-repo] \
        [--price-override '{"flash":[in,out,cacheR],...}']

Semantics pinned by the design authority:
- verdict per bash part (output text): ``BUILD SUCCESSFUL`` -> ok;
  ``BUILD FAILED`` -> fail; ``exit code N`` with N != 0 -> fail; otherwise
  unknown. unknown neither increments nor resets a fail streak.
- status: first ``STATUS:\\s*(\\w+)`` match in the session's LAST text part
  (ordered by time_created); missing -> ``none``.
- ticket: first ``proposals/<p>/issues/<id>.md`` match in the FIRST text part.
- bash commands are normalized (trim, collapse whitespace, truncate to 120
  chars) before counting repetitions.
- epoch bounds are strict (``<T``, ``>T``); ranges ``T1-T2`` are inclusive
  (a ts exactly at a boundary belongs to the right, closed range form).
- est_cost uses tier proxy prices $/M (input, output, cache read); tier is
  ``flash`` when the model id contains "flash", else ``flagship``.

Report semantics (ticket 02; design d-epoch / d-strata / d-cost):
- observations.md is read-only for report; report.md is fully replaced.
- epochs come from ``--epochs`` (never guessed); sessions outside every
  bound are ``unclassified``.
- strata are the objective ticket proxy: change-bullet count plus
  evidence-cmd family — L = >= 4 change bullets or any integrationTest /
  E2E / --rerun command; S = <= 2 change bullets with unit-level commands
  only (test --tests / pnpm test / go test / unittest / pytest class);
  M otherwise. Tickets that cannot be resolved under --project-root are
  ``unknown`` and counted in the report.
- runaway = steps > 150 or rep_max > 10 or dur_min > 30 (any one).
- medians use statistics.median (even n = mean of the two middle values).

Gate semantics (ticket 03; design d-decision-gates — pre-registered):
- gates consume observations rows + the aggregation only, never the DB
  (report stays offline-rerunnable); only the ``hardened`` epoch gates.
- observation window (local time): 2026-09-14 00:00 -> 2026-09-20 23:59;
  remaining days = window last day - report run day.
- G1 loop safety: hardened runaway events = 0 -> pass; any -> fail (alarm);
  hardened empty -> insufficient-n.
- G2 economics per stratum: flash cost median < flagship median x 0.7 with
  n >= 5 per side -> pass; ratio >= 0.7 -> fail (>= 2x -> rollback,
  otherwise extend observation); n < 5 -> insufficient-n.
- G3 duration per stratum: flash dur median <= flagship median x 1.5 ->
  pass; recorded only, never triggers rollback by itself.
- G4 recurrence circuit-break: hardened session with rep_max >= 20 or
  steps >= 400 (right-inclusive) -> fail (immediate-rollback alarm).
- closeout writes DECISION.md (three-way conclusion template) from the
  final report; rules change only via design d-decision-gates revision.
"""

